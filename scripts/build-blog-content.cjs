// Turns the Markdown articles in content/blog/ into lib/content/articles.ts, which the site imports.
// Run with: npm run blogs:build
//
// Each article is one file: content/blog/<category>/<number>-<url-slug>.md
// The top of the file holds its details between two lines of "---":
//   title, description, tags, keywords, cover (the scene for the cover image)
const fs = require("node:fs")
const path = require("node:path")

const root = path.join(__dirname, "..")
const source = path.join(root, "content/blog")
const categories = { ai: "AI", blockchain: "Blockchain", coding: "Coding" }
const published = "November 11, 2026"

function readArticle(folder, file) {
  const raw = fs.readFileSync(path.join(source, folder, file), "utf8").replace(/\r\n/g, "\n")
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw)
  if (!match) throw new Error(`Missing details block at the top of ${folder}/${file}`)
  const details = {}
  for (const line of match[1].split("\n")) {
    const colon = line.indexOf(":")
    if (colon > 0) details[line.slice(0, colon).trim()] = line.slice(colon + 1).trim()
  }
  for (const key of ["title", "description", "tags", "keywords", "cover"]) if (!details[key]) throw new Error(`Missing "${key}" in ${folder}/${file}`)
  const content = match[2].trim()
  const id = file.replace(/^\d+-/, "").replace(/\.md$/, "")

  // Questions and answers under "## FAQ" are also sent to search engines as structured data.
  const faq = []
  const faqSection = /\n## FAQ\n([\s\S]*?)(?=\n## |$)/.exec(content)
  if (faqSection) {
    for (const block of faqSection[1].split(/\n### /).slice(1)) {
      const [question, ...answer] = block.split("\n")
      faq.push({ question: question.trim(), answer: answer.join(" ").replace(/[*`]/g, "").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1").replace(/\s+/g, " ").trim() })
    }
  }

  return {
    id,
    title: details.title,
    excerpt: details.description,
    category: categories[folder],
    date: published,
    author: "Aakash Singh Rajput",
    image: `/blogs/generated/${id}.svg`,
    imageAlt: `Illustration for the article: ${details.title}`,
    tags: details.tags.split(",").map((tag) => tag.trim()),
    keywords: details.keywords.split(",").map((keyword) => keyword.trim()),
    cover: details.cover,
    faq,
    content,
  }
}

const groups = Object.keys(categories).map((folder) => fs.readdirSync(path.join(source, folder)).filter((file) => file.endsWith(".md")).sort().map((file) => readArticle(folder, file)))

// Mix the categories (AI, Blockchain, Coding, AI, ...) so the blog page shows a variety of topics.
const articles = []
for (let i = 0; i < Math.max(...groups.map((group) => group.length)); i++) for (const group of groups) if (group[i]) articles.push(group[i])

const output = `// Generated by scripts/build-blog-content.cjs from content/blog/. Do not edit by hand.\nimport type { BlogPost } from "../blog-types"\n\nexport const articles: BlogPost[] = ${JSON.stringify(articles, null, 2)}\n`
fs.writeFileSync(path.join(root, "lib/content/articles.ts"), output)
console.log(`Built ${articles.length} articles: ${groups.map((group, i) => `${group.length} ${Object.values(categories)[i]}`).join(", ")}.`)
